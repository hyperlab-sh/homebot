// keyHeader starts the private key file as age-keygen writes it: when it
// was made and the public key, then the private key on its own line.
const keyHeader = "# created: %s\n# public key: %s\n"

// InitKeys creates the repo's key pair and returns the public key. It asks
// for a passphrase twice on the terminal, or makes one up when the first
// answer is empty, and seals the private key with it (scrypt, age's default
// work factor) into private/identity.age; the public key goes to
// private/recipients.txt. The private key never touches the disk
// unencrypted. It refuses when either file exists. It writes
// private/.gitignore first when there is none (EnsurePrivateGitignore).
func InitKeys(ctx *app.Context) (string, error) {
	l := ctx.Layout()
	for _, p := range []string{l.Identity, l.Recipients} {
		info, err := fsx.LstatIfExists(p)
		if err != nil {
			return "", err
		}
		if info != nil {
			return "", fail.User(voice.Plain(ctx, msg.SecretsErrorKeysExist()))
		}
	}
	// Before anything else lands in private/: without its .gitignore, save
	// would stage every plaintext secret there (D14).
	if err := EnsurePrivateGitignore(ctx); err != nil {
		return "", err
	}
	workFactor, lowered, err := testWorkFactor(ctx.Env)
	if err != nil {
		return "", err
	}
	pass, err := newPassphrase(ctx)
	if err != nil {
		return "", err
	}
	recipient, err := age.NewScryptRecipient(pass)
	if err != nil {
		return "", err
	}
	if lowered {
		recipient.SetWorkFactor(workFactor)
	}
	id, err := age.GenerateX25519Identity()
	if err != nil {
		return "", err
	}
	public := id.Recipient().String()
	key := fmt.Appendf(make([]byte, 0, 512), keyHeader, ctx.Now().Format(time.RFC3339), public)
	key = append(append(key, id.String()...), '\n')
	defer clear(key)
	var sealed bytes.Buffer
	if err := encrypt(&sealed, key, recipient); err != nil {
		return "", fail.User(fail.Failure(voice.Plain(ctx, msg.SecretsErrorEncryptKey()), err.Error(), ""))
	}
	// The files are checked above, but the passphrase prompt can take a
	// while: they are published only if they still don't exist.
	if err := publishFile(l.Identity, sealed.Bytes(), 0o666); err != nil {
		return "", saveFailed(ctx, l.Identity, err)
	}
	if err := publishFile(l.Recipients, []byte(public+"\n"), 0o666); err != nil {
		// The publish can fail after recipients.txt is already in place
		// (removing the temp file or syncing the folder). Then both files
		// are there and match: removing identity.age now would leave a
		// recipient whose private key is gone, and every later lock would
		// seal secrets nobody can open.
		if got, readErr := os.ReadFile(l.Recipients); readErr == nil && string(got) == public+"\n" {
			return public, nil
		}
		_ = os.Remove(l.Identity)
		return "", saveFailed(ctx, l.Recipients, err)
	}
	return public, nil
}

// publishFile is fsx.PublishFile; tests replace it to fail after the write.
var publishFile = fsx.PublishFile

// encrypt appends data, encrypted to recipients, to dst.
func encrypt(dst *bytes.Buffer, data []byte, recipients ...age.Recipient) error {
	w, err := age.Encrypt(dst, recipients...)
	if err != nil {
		return err
	}
	if _, err := w.Write(data); err != nil {
		return err
	}
	return w.Close()
}

// saveFailed is the error for the key file p that could not be saved: it
// appeared since InitKeys checked, or writing it failed.
func saveFailed(ctx *app.Context, p string, err error) error {
	if errors.Is(err, fs.ErrExist) {
		return fail.User(voice.Plain(ctx, msg.SecretsErrorKeysExist()))
	}
	return fail.User(fail.Failure(voice.Plain(ctx, msg.SecretsErrorSaveKey(shownPath(ctx, p))), err.Error(), ""))
}

// newPassphrase asks for a new passphrase and its confirmation. An empty
// answer makes one up and shows it on the terminal only, as the age CLI did.
func newPassphrase(ctx *app.Context) (string, error) {
	t, err := openTerminal(ctx)
	if err != nil {
		return "", err
	}
	defer t.close()
	pass, err := t.secret(voice.Plain(ctx, msg.KeysPromptPassphrase()))
	if err != nil {
		return "", err
	}
	defer clear(pass)
	if len(pass) == 0 {
		made := madeUpPassphrase()
		if err := t.show(voice.Plain(ctx, msg.KeysStatusAutogenerated(made))); err != nil {
			return "", err
		}
		return made, nil
	}
	confirm, err := t.secret(voice.Plain(ctx, msg.KeysPromptConfirm()))
	if err != nil {
		return "", err
	}
	defer clear(confirm)
	if !bytes.Equal(pass, confirm) {
		return "", fail.User(voice.Plain(ctx, msg.KeysErrorMismatch()))
	}
	return string(pass), nil
}

// bip39 is the BIP39 English word list, the one the age CLI makes up
// passphrases from (filippo.io/age cmd/age/wordlist.go, BSD-3-Clause).
//
//go:embed bip39.txt
var bip39 string

var words = sync.OnceValue(func() []string { return strings.Fields(bip39) })

// madeUpPassphrase is ten random words from the list joined by hyphens, as
// the age CLI makes them: 110 bits.
func madeUpPassphrase() string {
	list := words()
	picked := make([]string, 10)
	var b [2]byte
	for i := range picked {
		// crypto/rand.Read never returns an error.
		_, _ = rand.Read(b[:])
		picked[i] = list[int(binary.BigEndian.Uint16(b[:]))%len(list)]
	}
	return strings.Join(picked, "-")
}
