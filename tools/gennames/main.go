// Command gennames writes the name lists used by the site's picker preview.
// The CLI remains authoritative because it also checks this machine's PATH.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"

	"github.com/hyperlab-sh/homebot/internal/cli"
	"github.com/hyperlab-sh/homebot/internal/config"
	"github.com/hyperlab-sh/homebot/internal/selfname"
)

const output = "docs/assets/js/reserved-names.json"

type names struct {
	Source  string   `json:"_source"`
	Syntax  syntax   `json:"syntax"`
	Homebot []string `json:"homebot"`
	Shell   []string `json:"shell"`
	Tools   []string `json:"tools"`
}

type syntax struct {
	Pattern   string `json:"pattern"`
	MinLength int    `json:"minLength"`
	MaxLength int    `json:"maxLength"`
}

func eligible(in []string) []string {
	out := make([]string, 0, len(in))
	for _, name := range in {
		if config.ValidName(name) {
			out = append(out, name)
		}
	}
	slices.Sort(out)
	return slices.Compact(out)
}

func generate() ([]byte, error) {
	value := names{
		Source:  "Generated by go run ./tools/gennames from CLI, shell, and tool reservations. Preview only; homebot checks the current machine before using a name.",
		Syntax:  syntax{Pattern: `^[a-z][a-z0-9-]*$`, MinLength: 2, MaxLength: 32},
		Homebot: eligible(cli.ReservedNames()),
		Shell:   eligible(selfname.ShellWords),
		Tools:   eligible(selfname.ToolNames),
	}
	data, err := json.MarshalIndent(value, "", "  ")
	return append(data, '\n'), err
}

func run(check bool, path string) error {
	want, err := generate()
	if err != nil {
		return err
	}
	if check {
		got, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(got, want) {
			return errors.New("reserved names are stale; run go run ./tools/gennames")
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, want, 0o644)
}

func main() {
	check := flag.Bool("check", false, "check that reserved-names.json is current")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "usage: gennames [-check]")
		os.Exit(2)
	}
	if err := run(*check, output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
