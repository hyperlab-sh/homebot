func TestRunWritesTheFiles(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "catalog.yaml"), tiny)
	if err := run(dir); err != nil {
		t.Fatal(err)
	}
	for name, want := range map[string]string{"messages_gen.go": tinyMessages, "samples_gen_test.go": tinySamples} {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		if d := cmp.Diff(want, string(got)); d != "" {
			t.Errorf("%s (-want +got):\n%s", name, d)
		}
	}
}

func TestRunLeavesCurrentFilesAlone(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "catalog.yaml"), tiny)
	if err := run(dir); err != nil {
		t.Fatal(err)
	}
	gen := filepath.Join(dir, "messages_gen.go")
	old := time.Unix(1_000_000_000, 0)
	if err := os.Chtimes(gen, old, old); err != nil {
		t.Fatal(err)
	}
	if err := run(dir); err != nil {
		t.Fatal(err)
	}
	if st, err := os.Stat(gen); err != nil || !st.ModTime().Equal(old) {
		t.Errorf("an unchanged file was rewritten (%v)", err)
	}
}

