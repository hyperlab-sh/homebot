func TestAccessorsRefuse(t *testing.T) {
	cases := []struct {
		name, messages, want string
	}{
		{"bad id", `[{id: Inbox, text: x}]`, "dotted lowercase"},
		{"single word id", `[{id: inbox, text: x}]`, "dotted lowercase"},
		{"id starting with a digit", `[{id: 1x.y, text: x}]`, "not an exported Go identifier"},
		{"duplicate id", `[{id: a.b, text: x}, {id: a.b, text: y}]`, "id given twice"},
		{"accessor clash", `[{id: a.b_c, text: x}, {id: a_b.c, text: y}]`, "also the name of a.b_c"},
		{"hand-written name", `[{id: neutral.name, text: x}]`, "clashes with a hand-written"},
		{"unparsable text", `[{id: a.b, text: "{x"}]`, "unclosed {"},
		{"undeclared placeholder", `[{id: a.b, text: "{x}"}]`, "{x} is not declared"},
		{"plural of a string", `[{id: a.b, text: "{n:a|b}", placeholders: [{name: n, type: string}]}]`, "needs an int placeholder"},
		{"unused placeholder", `[{id: a.b, text: "x", placeholders: [{name: n, type: int}]}]`, "does not use it"},
		{"bad type", `[{id: a.b, text: "{n}", placeholders: [{name: n, type: number}]}]`, `type "number"`},
		{"bad placeholder name", `[{id: a.b, text: "x", placeholders: [{name: N, type: int, optional: true}]}]`, "must be lowercase"},
		{"declared twice", `[{id: a.b, text: "{n}", placeholders: [{name: n, type: int}, {name: n, type: int}]}]`, "declared twice"},
		{"bot not optional", `[{id: a.b, text: "{bot}", placeholders: [{name: bot, type: string}]}]`, "bot must be an optional string"},
		{"self optional", `[{id: a.b, text: "{self}", placeholders: [{name: self, type: string, optional: true}]}]`, "self must be a string that is not optional"},
		{"self fixed", `[{id: a.b, text: "{self}", placeholders: [{name: self, type: string, value: "homebot"}]}]`, "self must be a string that is not optional"},
		{"self undeclared", `[{id: a.b, text: "{self}"}]`, "{self} is not declared"},
		{"other placeholder in append", `[{id: a.b, text: x, append: " {name}"}]`, "no placeholder but {self}"},
		{"other placeholder in value", `[{id: a.b, text: "{cmd}", placeholders: [{name: cmd, type: string, value: "{other} next"}]}]`, "a value holds no placeholder but {self}"},
		{"same parameter", `[{id: a.b, text: "{a_b} {a__b}", placeholders: [{name: a_b, type: int}, {name: a__b, type: int}]}]`, "both the parameter"},
		{"braces in append", `[{id: a.b, text: x, append: " {n}"}]`, "must be literal"},
		{"value on an int", `[{id: a.b, text: "{n}", placeholders: [{name: n, type: int, value: "3"}]}]`, "must be a string, not int"},
		{"value on a path", `[{id: a.b, text: "{p}", placeholders: [{name: p, type: path, value: "~/x"}]}]`, "must be a string, not path"},
		{"value on an optional", `[{id: a.b, text: "{s}", placeholders: [{name: s, type: string, optional: true, value: "x"}]}]`, "cannot be optional"},
		{"value with forms", `[{id: a.b, text: "{s}", placeholders: [{name: s, type: string, forms: "a|b", value: "x"}]}]`, "cannot have plural forms"},
		{"value unused", `[{id: a.b, text: "x", placeholders: [{name: s, type: string, value: "x"}]}]`, "has a value, but the text does not use it"},
		{"an empty value", `[{id: a.b, text: "{s}", placeholders: [{name: s, type: string, value: ""}]}]`, "has an empty value"},
		{"value on bot", `[{id: a.b, text: "{bot}", placeholders: [{name: bot, type: string, value: "x"}]}]`, "bot must be an optional string"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			f, err := catalog.Load([]byte("messages: " + c.messages))
			if err != nil {
				t.Fatal(err)
			}
			_, err = accessors(f)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("err = %v, want it to mention %q", err, c.want)
			}
		})
	}
}

func TestAccessorsReportEveryProblem(t *testing.T) {
	f, err := catalog.Load([]byte(`messages: [{id: a.b, text: "{x}"}, {id: c.d, text: "{y"}]`))
	if err != nil {
		t.Fatal(err)
	}
	_, err = accessors(f)
	if err == nil || !strings.Contains(err.Error(), "a.b:") || !strings.Contains(err.Error(), "c.d:") {
		t.Errorf("err = %v, want both entries named", err)
	}
}

// A fixed placeholder is not a parameter: the accessor fills its value in,
// beside the parameters, in declaration order.
func TestAccessorsFixAValue(t *testing.T) {
	f, err := catalog.Load([]byte(`messages: [{id: a.b, text: "{n} see {cmd}{ext}", placeholders: [{name: cmd, type: string, value: "homebot ", meaning: "m (fixed)"}, {name: n, type: int}, {name: ext, type: string, value: ".yml", meaning: "m (fixed)"}]}]`))
	if err != nil {
		t.Fatal(err)
	}
	as, err := accessors(f)
	if err != nil {
		t.Fatal(err)
	}
	want := []param{{name: "cmd", typ: catalog.String, fixed: true, value: "homebot "}, {name: "n", ident: "n", typ: catalog.Int}, {name: "ext", typ: catalog.String, fixed: true, value: ".yml"}}
	if d := cmp.Diff(want, as[0].params, cmp.AllowUnexported(param{})); d != "" {
		t.Errorf("params (-want +got):\n%s", d)
	}
	if args := as[0].args(); len(args) != 1 || args[0].name != "n" {
		t.Errorf("args = %+v, want only n", args)
	}
}

func TestGoName(t *testing.T) {
	for in, want := range map[string]string{
		"inbox.header.count":       "InboxHeaderCount",
		"help.unpack.example.1":    "HelpUnpackExample1",
		"remote.ssh_url.os_env":    "RemoteSSHURLOSEnv",
		"cli.error.unknown_cli":    "CLIErrorUnknownCLI",
		"inbox.helper_stale.title": "InboxHelperStaleTitle",
	} {
		if got := goName(in, true); got != want {
			t.Errorf("goName(%q, true) = %q, want %q", in, got, want)
		}
	}
	for in, want := range map[string]string{
		"n": "n", "key_path": "keyPath", "ssh_url": "sshURL", "url": "url", "os_env": "osEnv", "repo_abs": "repoAbs",
	} {
		if got := goName(in, false); got != want {
			t.Errorf("goName(%q, false) = %q, want %q", in, got, want)
		}
	}
}

