// TestGeneratedFilesAreCurrent fails when catalog.yaml changed without
// go generate, or when the generator changed without regenerating.
func TestGeneratedFilesAreCurrent(t *testing.T) {
	dir := filepath.Join("..", "..", "internal", "msg")
	files, err := generate(dir)
	if err != nil {
		t.Fatal(err)
	}
	for name, want := range files {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != string(want) {
			t.Errorf("internal/msg/%s is stale: run go generate ./internal/msg", name)
		}
	}
}

