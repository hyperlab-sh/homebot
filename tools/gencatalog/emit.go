package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"golang.org/x/text/language"

	"github.com/hyperlab-sh/homebot/internal/msg/catalog"
)

const header = "// Code generated by gencatalog from catalog.yaml. DO NOT EDIT.\n\n"

// goTypes are the parameter types of the placeholder types. A duration is a
// message too (format.ago.*, or a word such as "never"), so it is a Text.
var goTypes = map[catalog.Type]string{
	catalog.Int:      "int",
	catalog.String:   "string",
	catalog.Path:     "string",
	catalog.Duration: "Text",
}

// catalogTypes are the names of the placeholder types in package catalog.
var catalogTypes = map[catalog.Type]string{
	catalog.Int:      "catalog.Int",
	catalog.String:   "catalog.String",
	catalog.Path:     "catalog.Path",
	catalog.Duration: "catalog.Duration",
}

// messagesFile is messages_gen.go: the table of entries, with the metadata
// msg.Entries and msg.Build read, and one accessor per entry.
func messagesFile(as []accessor, samples sampler) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header + "package msg\n\n")
	if usesCatalog(as) {
		b.WriteString("import \"github.com/hyperlab-sh/homebot/internal/msg/catalog\"\n\n")
	}
	b.WriteString("var messages = [...]message{\n")
	for _, a := range as {
		e := a.entry
		fmt.Fprintf(&b, "\t{id: %s", strconv.Quote(e.ID))
		if e.Kind != "" {
			fmt.Fprintf(&b, ", kind: %s", strconv.Quote(e.Kind))
		}
		if e.Class != "" {
			fmt.Fprintf(&b, ", class: %s", strconv.Quote(e.Class))
		}
		fmt.Fprintf(&b, ", text: %s", strconv.Quote(e.Text))
		if e.Append != "" {
			fmt.Fprintf(&b, ", append: %s", strconv.Quote(e.Append))
		}
		if e.Persona {
			b.WriteString(", persona: true")
		}
		if len(e.Placeholders) > 0 {
			b.WriteString(", slots: []Slot{")
			for j, p := range e.Placeholders {
				if j > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "{Name: %s, Type: %s", strconv.Quote(p.Name), catalogTypes[p.Type])
				if p.Optional {
					b.WriteString(", Optional: true")
				}
				if v, fixed := p.Fixed(); fixed {
					fmt.Fprintf(&b, ", Value: %s", strconv.Quote(v))
				}
				if p.Meaning != "" {
					fmt.Fprintf(&b, ", Meaning: %s", strconv.Quote(p.Meaning))
				}
				if v := samples.value(p); v != "" {
					fmt.Fprintf(&b, ", Sample: %s", strconv.Quote(v))
				}
				b.WriteString("}")
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	for i, a := range as {
		fmt.Fprintf(&b, "\n// %s is %s: %s.\nfunc %s(", a.name, a.entry.ID, strconv.Quote(a.entry.Text), a.name)
		for j, p := range a.args() {
			if j > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%s %s", p.ident, goTypes[p.typ])
		}
		fmt.Fprintf(&b, ") Text {\n\treturn Text{m: &messages[%d]", i)
		if len(a.params) > 0 {
			b.WriteString(", args: []Arg{")
			for j, p := range a.params {
				if j > 0 {
					b.WriteString(", ")
				}
				value := p.ident
				if p.fixed {
					value = strconv.Quote(p.value)
				}
				fmt.Fprintf(&b, "{%s, %s, %s}", strconv.Quote(p.name), catalogTypes[p.typ], value)
			}
			b.WriteString("}")
		}
		b.WriteString("}\n}\n")
	}
	return gofmt("messages_gen.go", b.Bytes())
}

func usesCatalog(as []accessor) bool {
	for _, a := range as {
		if len(a.entry.Placeholders) > 0 {
			return true
		}
	}
	return false
}

// sampler gives each placeholder the sample value previews show, the same
// values samples_gen_test.go passes the accessors: counts 3, strings
// <name>, paths /path/to/name, durations as format.ago.hours says 3 hours.
// A fixed placeholder's sample is its value; bot and self have none, the
// renderer fills them.
type sampler struct {
	// duration is the catalog's English for 3 hours ago.
	duration string
}

func newSampler(f *catalog.File) sampler {
	for _, e := range f.Messages {
		if e.ID != durationSample || len(e.Placeholders) != 1 {
			continue
		}
		tmpl, err := catalog.Parse(e.Text)
		if err != nil {
			break
		}
		return sampler{duration: tmpl.Format(language.English, map[string]any{e.Placeholders[0].Name: 3}, nil)}
	}
	return sampler{}
}

// durationSample is the message a duration's sample is said with.
const durationSample = "format.ago.hours"

func (s sampler) value(p catalog.Placeholder) string {
	if v, fixed := p.Fixed(); fixed {
		return strings.ReplaceAll(v, catalog.SelfRef, "homebot")
	}
	if p.Name == catalog.Bot || p.Name == catalog.Self {
		return ""
	}
	switch p.Type {
	case catalog.Int:
		return "3"
	case catalog.String:
		return "<" + p.Name + ">"
	case catalog.Path:
		return "/path/to/" + p.Name
	case catalog.Duration:
		if s.duration != "" {
			return s.duration
		}
		return "<" + p.Name + ">"
	}
	return ""
}

// samplesFile is samples_gen_test.go: every accessor called with sample
// values the placeholder types decide, and once more with every count at 1
// when the text has a plural.
func samplesFile(as []accessor) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header + "package msg_test\n\n")
	b.WriteString("import \"github.com/hyperlab-sh/homebot/internal/msg\"\n\n")
	b.WriteString("var samples = []sample{\n")
	for _, a := range as {
		writeSample(&b, a, a.entry.ID, 3)
		if a.plural {
			writeSample(&b, a, a.entry.ID+" (1)", 1)
		}
	}
	b.WriteString("}\n")
	return gofmt("samples_gen_test.go", b.Bytes())
}

func writeSample(b *bytes.Buffer, a accessor, label string, count int) {
	fmt.Fprintf(b, "\t{%s, msg.%s(", strconv.Quote(label), a.name)
	for j, p := range a.args() {
		if j > 0 {
			b.WriteString(", ")
		}
		switch p.typ {
		case catalog.Int:
			b.WriteString(strconv.Itoa(count))
		case catalog.String:
			b.WriteString(strconv.Quote("<" + p.name + ">"))
		case catalog.Path:
			b.WriteString(strconv.Quote("/path/to/" + p.name))
		case catalog.Duration:
			fmt.Fprintf(b, "msg.FormatAgoHours(%d)", count)
		}
	}
	b.WriteString(")},\n")
}

func gofmt(name string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("formatting %s: %w", name, err)
	}
	return out, nil
}
