const markerEnd = "<!-- gendocs:end -->"

type generatedDoc struct {
	path, marker string
	content      []byte
}

// writeDocs builds all reference output in memory before writing anything.
// -check is read-only and names every stale path, including missing files.
func writeDocs(root string, check bool) error {
	tree, cleanup, err := newTree()
	if err != nil {
		return err
	}
	defer cleanup()
	files := []generatedDoc{
		{"docs/pages/reference/commands.md", "commands", commandsSection(cli.ManEntries(tree))},
		{"docs/pages/reference/config.md", "config", configSection()},
		{"docs/pages/reference/personas.md", "personas", personaSection()},
		{"docs/pages/reference/messages.md", "", messagesPage()},
	}
	home, err := jsonDoc(homebotSchema())
	if err != nil {
		return err
	}
	personas, err := jsonDoc(personaSchema())
	if err != nil {
		return err
	}
	files = append(files,
		generatedDoc{"docs/landing/schema/homebot.json", "", home},
		generatedDoc{"docs/landing/schema/persona.json", "", personas},
	)
	var stale []string
	for _, f := range files {
		path := filepath.Join(root, f.path)
		want := f.content
		if f.marker != "" {
			old, err := os.ReadFile(path)
			if err != nil {
				return fmt.Errorf("%s: %w", f.path, err)
			}
			want, err = replaceSection(f.path, old, f.marker, want)
			if err != nil {
				return err
			}
		}
		old, err := os.ReadFile(path)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("%s: %w", f.path, err)
		}
		if bytes.Equal(old, want) && err == nil {
			continue
		}
		if check {
			stale = append(stale, f.path)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			return fmt.Errorf("%s: %w", f.path, err)
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("generated docs differ: %s", strings.Join(stale, ", "))
	}
	return nil
}

func replaceSection(path string, old []byte, name string, body []byte) ([]byte, error) {
	start := "<!-- gendocs:start " + name + " -->"
	s, e := bytes.Index(old, []byte(start)), bytes.Index(old, []byte(markerEnd))
	if s < 0 || e < 0 || e < s || bytes.Count(old, []byte(start)) != 1 || bytes.Count(old, []byte(markerEnd)) != 1 {
		return nil, fmt.Errorf("%s: missing or duplicate gendocs %s markers", path, name)
	}
	var out bytes.Buffer
	out.Write(old[:s+len(start)])
	out.WriteByte('\n')
	out.Write(bytes.TrimSpace(body))
	out.WriteByte('\n')
	out.Write(old[e:])
	return out.Bytes(), nil
}

func markdown(s string) string {
	s = html.EscapeString(s)
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\n", "<br>")
	return s
}

func literalCell(s string) string {
	// docmd's link validator scans even code spans and HTML code elements.
	// Entities preserve literal brackets when rendered without presenting a
	// Markdown link token to that scan.
	s = html.EscapeString(s)
	s = strings.ReplaceAll(s, "[", "&#91;")
	s = strings.ReplaceAll(s, "]", "&#93;")
	s = strings.ReplaceAll(s, "|", "&#124;")
	s = strings.ReplaceAll(s, "\n", "<br>")
	return "<code>" + s + "</code>"
}

func commandsSection(entries []cli.ManEntry) []byte {
	var b strings.Builder
	b.WriteString("<!-- Generated by go run ./tools/gendocs docs; do not edit this section. -->\n\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "### %s\n\n", markdown(e.Name))
		fmt.Fprintf(&b, "**Usage:** `%s`\n\n", strings.ReplaceAll(markdown(e.Usage), "`", "&#96;"))
		fmt.Fprintf(&b, "%s\n\n", markdown(e.Description))
		if len(e.Options) > 0 {
			b.WriteString("| Option | Meaning |\n|---|---|\n")
			for _, o := range e.Options {
				fmt.Fprintf(&b, "| `%s` | %s |\n", strings.ReplaceAll(markdown(o.Label), "`", "&#96;"), markdown(o.Meaning))
			}
			b.WriteByte('\n')
		}
		if len(e.Examples) > 0 {
			b.WriteString("| Example | Meaning |\n|---|---|\n")
			for _, ex := range e.Examples {
				fmt.Fprintf(&b, "| `%s` | %s |\n", strings.ReplaceAll(markdown(ex.Label), "`", "&#96;"), markdown(ex.Meaning))
			}
			b.WriteByte('\n')
		}
	}
	return []byte(b.String())
}

func configSection() []byte {
	var b strings.Builder
	b.WriteString("<!-- Generated by go run ./tools/gendocs docs; do not edit this section. -->\n\n")
	b.WriteString("| Path | Type | Default | Values | Description | Since |\n|---|---|---|---|---|---|\n")
	for _, k := range config.Keys {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n",
			markdown(k.Path), k.Kind, markdown(k.Default), markdown(strings.Join(k.Allowed, ", ")),
			markdown(voice.Record(nil, config.Description(k))), markdown(k.Added))
	}
	return []byte(b.String())
}

func messagesPage() []byte {
	var b strings.Builder
	b.WriteString("---\ntitle: \"Message catalog\"\ndescription: \"Generated message IDs, English text and placeholders.\"\n---\n\n")
	b.WriteString("# Message catalog\n\nGenerated by `go run ./tools/gendocs docs`; do not edit this page.\n\n")
	entries := msg.Entries()
	slices.SortFunc(entries, func(a, b msg.Meta) int { return strings.Compare(a.ID, b.ID) })
	area := ""
	for _, e := range entries {
		part, _, _ := strings.Cut(e.ID, ".")
		if part != area {
			area = part
			fmt.Fprintf(&b, "## %s\n\n| ID | Kind | Class | Placeholders | English |\n|---|---|---|---|---|\n", markdown(area))
		}
		var slots []string
		for _, s := range e.Slots {
			label := s.Name + ": " + string(s.Type)
			if s.Optional {
				label += " (optional)"
			}
			if s.Value != "" {
				label += " = " + s.Value
			}
			slots = append(slots, label)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", markdown(e.ID), markdown(e.Kind), markdown(e.Class), markdown(strings.Join(slots, ", ")), literalCell(e.Text))
	}
	return []byte(b.String())
}

func personaSection() []byte {
	var b strings.Builder
	b.WriteString("<!-- Generated by go run ./tools/gendocs docs; do not edit this section. -->\n\n")
	b.WriteString("### Fields\n\n| Field | Type | Required | Meaning |\n|---|---|---|---|\n")
	for _, f := range persona.Fields() {
		required := "no"
		if f.Required {
			required = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", markdown(f.Name), markdown(f.Type), required, markdown(f.Description))
	}
	b.WriteString("\n### Voice IDs\n\n| ID | Kind | English |\n|---|---|---|\n")
	entries := msg.Entries()
	slices.SortFunc(entries, func(a, b msg.Meta) int { return strings.Compare(a.ID, b.ID) })
	for _, e := range entries {
		if e.Persona {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", markdown(e.ID), markdown(e.Kind), literalCell(e.Text))
		}
	}
	return []byte(b.String())
}

func jsonDoc(v any) ([]byte, error) {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}
